package com.wildenglish.app.audiobook.data

import android.content.Context
import com.wildenglish.app.audiobook.data.VoiceCache.readRoots
import java.io.File
import java.util.UUID

/**
 * On-device cache of synthesized sentence audio (MP3).
 *
 * Storage is **SD-card first**: new audio is written under [AppStorage.sdcardRoot] into
 * `voice_cache/<bookId>/c<chapter>/<sentence>.mp3`. That root is pinned across updates/reboots,
 * so a reordered [getExternalFilesDirs] or an ejected card can no longer make already-generated
 * audio look lost. Only an uninstall / clear-data removes it (same as the internal filesDir).
 * If no usable external volume exists, writes fall back to the book's own internal directory.
 *
 * Audio already generated by older versions lives inside the book directory at
 * `tts/`. Those legacy files remain readable (read checks external first, then
 * internal) so upgrading never re-downloads a whole book; new files simply go
 * to the SD card instead.
 *
 * A `.ready` marker records that pre-generation finished. Re-import / delete
 * clear the external cache explicitly ([clearForId]) because replacing the book
 * directory no longer removes audio stored outside it.
 *
 * Writes are atomic (unique temp file + rename) because the background
 * pre-generator and the live playback fallback can target the same sentence.
 *
 * Per-role dubbing means one sentence can be read by different voices, so the
 * voice name is part of the file name (`<sentence>.<voice>.mp3`). Audio written
 * by the old single-voice version (`<sentence>.mp3`) is still accepted for
 * narrator lines, whose voice has not changed.
 */
object VoiceCache {

    private const val DIR = "tts"
    private const val READY = ".ready"
    private const val CACHE_VERSION = "2"

    /** One sentence slot to verify: which voice it must have been generated with. */
    data class Slot(val chapterIndex: Int, val sentenceIndex: Int, val voice: String)

    @Volatile
    private var externalRoot: File? = null

    /** Resolves the pinned SD-card root; safe to call repeatedly (idempotent, re-checks each time). */
    fun init(context: Context) {
        val root = AppStorage.sdcardRoot(context.applicationContext)
            ?.let { File(it, AppStorage.VOICE_CACHE_DIR) }
        externalRoot = root
    }

    /** Preferred (external) root for a book, or the legacy internal root. */
    fun root(book: Audiobook): File = root(book.dir)

    fun root(dir: File): File = externalBook(dir) ?: internalBook(dir)

    private fun externalBook(dir: File): File? = externalRoot?.let { File(it, dir.name) }

    private fun internalBook(dir: File): File = File(dir, DIR)

    /** Roots to read from, in priority order (external first, then legacy). */
    private fun readRoots(dir: File): List<File> =
        listOfNotNull(externalBook(dir), internalBook(dir))

    /** Same as [readRoots] for a book, plus an alternate folder named after [Audiobook.id]. */
    private fun readRoots(book: Audiobook): List<File> {
        val roots = readRoots(book.dir).toMutableList()
        if (book.id.isNotBlank() && book.id != book.dir.name) {
            externalRoot?.let { root ->
                val alt = File(root, book.id)
                if (alt !in roots) roots.add(alt)
            }
        }
        return roots
    }

    /** Root to write to: external when usable, otherwise internal. */
    private fun targetRoot(dir: File): File {
        val ext = externalBook(dir)
        if (ext != null && (ext.isDirectory || ext.mkdirs()) && ext.canWrite()) return ext
        return internalBook(dir)
    }

    private fun audioFile(
        root: File,
        chapterIndex: Int,
        sentenceIndex: Int,
        voice: String?,
    ): File {
        val name = if (voice.isNullOrBlank()) {
            "$sentenceIndex.mp3"
        } else {
            "$sentenceIndex.${voiceKey(voice)}.mp3"
        }
        return File(File(root, "c$chapterIndex"), name)
    }

    /** Stable, file-name-safe token for a voice (`zh-CN-YunxiNeural` -> `zh-CN-Yunxi`). */
    private fun voiceKey(voice: String): String =
        voice.removeSuffix("Neural").replace(Regex("[^A-Za-z0-9-]"), "-")

    /** Files that may hold this sentence's audio for [voice], best match first. */
    private fun candidateFiles(
        root: File,
        chapterIndex: Int,
        sentenceIndex: Int,
        voice: String?,
    ): List<File> {
        val primary = audioFile(root, chapterIndex, sentenceIndex, voice)
        // Legacy single-voice audio is only valid when the line still uses the
        // narrator voice it was synthesized with.
        if (voice.isNullOrBlank() || !VoiceConfig.isLegacyDefaultVoice(voice)) {
            return listOf(primary)
        }
        return listOf(primary, audioFile(root, chapterIndex, sentenceIndex, null))
    }

    fun isReady(book: Audiobook): Boolean = readRoots(book).any { r ->
        runCatching {
            val marker = File(r, READY)
            marker.isFile && marker.readText().trim().startsWith(CACHE_VERSION)
        }.getOrDefault(false)
    }

    /**
     * True when every non-empty sentence already has a cached file. If so, writes
     * the `.ready` marker so the next launch will not walk the book again.
     */
    fun confirmReady(book: Audiobook, slots: List<Slot>): Boolean {
        if (isReady(book)) return true
        if (slots.any { (chapter, sentence, voice) ->
                !hasFile(book.dir, chapter, sentence, voice)
            }
        ) {
            return false
        }
        markReady(book)
        return true
    }

    fun markReady(book: Audiobook) {
        runCatching {
            val dir = targetRoot(book.dir)
            if (!dir.isDirectory && !dir.mkdirs()) return
            File(dir, READY).writeText(CACHE_VERSION)
        }
    }

    /** Clears generated audio (e.g. before regenerating). Keeps the book itself. */
    fun clear(book: Audiobook) {
        readRoots(book.dir).forEach { r -> runCatching { r.deleteRecursively() } }
    }

    /** Clears audio stored outside the book dir for a re-imported / deleted id. */
    fun clearForId(id: String) {
        externalRoot?.let { runCatching { File(it, id).deleteRecursively() } }
    }

    /** Cheap existence check used to decide whether to show the buffering state. */
    fun hasFile(
        dir: File?,
        chapterIndex: Int,
        sentenceIndex: Int,
        voice: String? = null,
    ): Boolean {
        if (dir == null) return false
        return readRoots(dir).any { r ->
            candidateFiles(r, chapterIndex, sentenceIndex, voice).any { file ->
                runCatching { file.isFile && file.length() > 0 }.getOrDefault(false)
            }
        }
    }

    /** Returns cached MP3 bytes, or null when missing/empty/corrupt. */
    fun get(
        dir: File?,
        chapterIndex: Int,
        sentenceIndex: Int,
        voice: String? = null,
    ): ByteArray? {
        if (dir == null) return null
        for (r in readRoots(dir)) {
            for (file in candidateFiles(r, chapterIndex, sentenceIndex, voice)) {
                val bytes = runCatching {
                    if (!file.isFile || file.length() <= 0) null else file.readBytes()
                }.getOrNull()
                if (bytes != null) return bytes
            }
        }
        return null
    }

    /** Atomically stores MP3 bytes for one sentence. No-op if already cached. */
    fun put(
        dir: File?,
        chapterIndex: Int,
        sentenceIndex: Int,
        voice: String?,
        bytes: ByteArray,
    ) {
        if (dir == null || bytes.isEmpty()) return
        // A late write from a cancelled job must not recreate a deleted book dir.
        if (!File(dir, "manifest.json").isFile) return
        // Already cached (externally or in the legacy internal cache): keep it,
        // so upgrading does not duplicate storage or re-copy old audio.
        if (hasFile(dir, chapterIndex, sentenceIndex, voice)) return
        runCatching {
            val target = audioFile(targetRoot(dir), chapterIndex, sentenceIndex, voice)
            val parent = target.parentFile ?: return
            if (!parent.isDirectory && !parent.mkdirs()) return
            val tmp = File(parent, target.name + "." + UUID.randomUUID() + ".tmp")
            tmp.writeBytes(bytes)
            if (!tmp.renameTo(target)) {
                // Another writer (pre-generator or playback) may have won the race.
                if (!target.isFile || target.length() <= 0) {
                    tmp.copyTo(target, overwrite = true)
                }
                tmp.delete()
            }
        }
    }

}
